impl Message {
    pub(super) fn for_avd(
        id: &str,
        event: fn(android_hub_domain::DeviceId) -> Self,
    ) -> Option<Self> {
        android_hub_domain::EmulatorId::new(id)
            .ok()
            .map(|id| event(android_hub_domain::DeviceId::Emulator(id)))
    }
}
